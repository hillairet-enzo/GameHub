export function icon(name: keyof typeof ICONS | string, size = 20): HTMLElement {
  const span = document.createElement('span');
  span.className = 'icon';
  span.style.width = span.style.height = `${size}px`;
  span.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] ?? ''}</svg>`;
  return span;
}

// ---------- formatting ----------

export function fmtDuration(seconds: number): string {
  if (!seconds || seconds < 60) return t('time.lessThanMinute');
  const minutes = Math.floor(seconds / 60);
  if (minutes < 60) return `${minutes} min`;
  const hours = Math.floor(minutes / 60);
  return `${hours} h ${String(minutes % 60).padStart(2, '0')}`;
}

export function fmtAgo(unixSeconds: number): string {
  if (!unixSeconds) return t('time.never');
  const diff = Math.max(0, Math.floor(Date.now() / 1000) - unixSeconds);
  const rtf = new Intl.RelativeTimeFormat(lang(), { numeric: 'auto' });
  if (diff < 90) return rtf.format(0, 'second');
  if (diff < 3600) return rtf.format(-Math.round(diff / 60), 'minute');
  if (diff < 86400) return rtf.format(-Math.round(diff / 3600), 'hour');
  if (diff < 86400 * 30) return rtf.format(-Math.round(diff / 86400), 'day');
  if (diff < 86400 * 365) return rtf.format(-Math.round(diff / (86400 * 30)), 'month');
  return rtf.format(-Math.round(diff / (86400 * 365)), 'year');
}

export function fmtSize(bytes: number): string {
  if (!bytes) return '';
  const gb = bytes / 1024 ** 3;
  if (gb >= 1) return `${gb.toFixed(1)} GB`;
  return `${Math.max(1, Math.round(bytes / 1024 ** 2))} MB`;
}

export function wait(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

export function hashHue(text: string): number {
  let hash = 0;
  for (const ch of text) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return hash % 360;
}

// ---------- toasts ----------

export function toast(message: string, kind: 'info' | 'ok' | 'error' = 'info', ms = 3600): void {
  const layer = document.getElementById('layer-toast');
  if (!layer) return;
  const el = h('div', { class: `toast toast-${kind}`, role: 'status' }, icon(kind === 'error' ? 'alert' : kind === 'ok' ? 'check' : 'info', 18), h('span', null, message));
  layer.appendChild(el);
  requestAnimationFrame(() => el.classList.add('is-in'));
  setTimeout(() => {
    el.classList.remove('is-in');
    setTimeout(() => el.remove(), 400);
  }, ms);
}
