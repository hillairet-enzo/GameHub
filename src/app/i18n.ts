const dictionaries: Record<'en' | 'fr', Dict> = { en, fr };
let current: 'en' | 'fr' = 'en';

function system(): 'en' | 'fr' {
  const languages = typeof navigator !== 'undefined' ? [navigator.language, ...(navigator.languages ?? [])] : [];
  return languages.some((l) => l?.toLowerCase().startsWith('fr')) ? 'fr' : 'en';
}

export function setLanguage(pref: LanguagePref): void {
  current = pref === 'auto' ? system() : pref;
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const lang = (): 'en' | 'fr' => current;

export const has = (key: string): boolean => key in dictionaries[current];

export function t(key: string, vars?: Record<string, string | number>): string {
  // `key.one` holds the singular form (French also uses it for 0).
  const n = vars?.n;
  const one = typeof n === 'number' && (n === 1 || (current === 'fr' && n === 0)) ? `${key}.one` : null;
  const text = (one && (dictionaries[current][one] ?? en[one])) || dictionaries[current][key] || en[key] || key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : text;
}

/** Turns a `code|detail` backend error into a sentence the user can act on. */
export function errorMessage(error: unknown): string {
  const raw = error instanceof Error ? error.message : String(error);
  const [code, ...rest] = raw.split('|');
  const detail = rest.join('|');
  const key = `error.${rest.length ? code : 'unknown'}`;
  return t(has(key) ? key : 'error.unknown', { detail: rest.length ? detail : raw });
}
